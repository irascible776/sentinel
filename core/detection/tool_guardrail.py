"""
Developer 1 & 2 — Pillar IV: Agentic Runtime Tool Guardrail
Integrates deterministic SSRF/cloud metadata defense, recursive AST deobfuscation,
and Qwen2.5-Coder transformer classification to inspect autonomous agent tool execution.
"""

import os
import time
import json
import threading
import hashlib
from collections import OrderedDict
from typing import Dict, Any, Optional

from core.detection.guardrails.ssrf_filter import SSRFFilter
from core.detection.guardrails.ast_normalizer import PayloadNormalizer, iter_strings


class AgenticToolGuardrail:
    """
    Inline security engine inspecting tool-call arguments generated by LLM agents
    before execution on host systems or corporate databases.
    """
    def __init__(self, model_dir: Optional[str] = None):
        self.model_dir = model_dir or os.getenv(
            "TOOL_GUARDRAIL_MODEL_DIR",
            os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(__file__))), "sentinel_model")
        )
        self.device = "cpu"
        self._tokenizer = None
        self._model = None
        self._model_load_failed = False
        self._load_lock = threading.Lock()
        self._cache_lock = threading.Lock()
        self._cache: OrderedDict = OrderedDict()
        self._cache_max: int = 1024

    def _lazy_load_model(self):
        """Lazy-loads Qwen2.5-Coder sequence classifier on CPU with full mutex locking."""
        if self._model is not None or self._model_load_failed:
            return

        with self._load_lock:
            # Re-check under lock
            if self._model is not None or self._model_load_failed:
                return

            if not os.path.exists(self.model_dir):
                self._model_load_failed = True
                return

            safetensors_path = os.path.join(self.model_dir, "model.safetensors")
            if not os.path.exists(safetensors_path):
                self._model_load_failed = True
                return

            # Pre-flight check: verify safetensors header integrity without reading entire file
            try:
                import struct
                with open(safetensors_path, "rb") as f:
                    header_len = struct.unpack("<Q", f.read(8))[0]
                    if header_len > 100_000_000:  # 100MB header size sanity cap
                        self._model_load_failed = True
                        return
                    header = json.loads(f.read(header_len).decode("utf-8"))
                    max_offset = max(
                        (v["data_offsets"][1] for v in header.values() if isinstance(v, dict) and "data_offsets" in v),
                        default=0
                    )
                    expected_size = 8 + header_len + max_offset
                    f.seek(0, 2)
                    actual_size = f.tell()
                    if actual_size < expected_size:
                        self._model_load_failed = True
                        return
            except Exception:
                self._model_load_failed = True
                return

            try:
                import torch
                from transformers import AutoTokenizer, AutoModelForSequenceClassification

                torch.set_num_threads(2)
                tok = AutoTokenizer.from_pretrained(
                    self.model_dir,
                    local_files_only=True
                )
                mdl = AutoModelForSequenceClassification.from_pretrained(
                    self.model_dir,
                    dtype=torch.float32,
                    local_files_only=True
                ).to(self.device)
                mdl.eval()

                # Atomically publish to instance only when completely initialized
                self._tokenizer = tok
                self._model = mdl
            except Exception:
                self._model_load_failed = True

    def _format_tool_call_string(self, tool_name: str, arguments: Any) -> str:
        """Formats arbitrary tool parameters into standard agentic tool signatures."""
        if isinstance(arguments, dict):
            if "cmd" in arguments:
                return f'run_terminal_command(cmd="{arguments["cmd"]}")'
            elif "query" in arguments:
                return f'execute_sql(query="{arguments["query"]}")'
            elif "url" in arguments:
                return f'http_get(url="{arguments["url"]}")'
            elif "path" in arguments:
                return f'read_file(path="{arguments["path"]}")'
            else:
                serialized = json.dumps(arguments, ensure_ascii=False)
                return f'{tool_name}({serialized})'
        else:
            arg_str = str(arguments).strip()
            norm_tool = tool_name.lower()
            if any(k in norm_tool for k in ["bash", "sh", "terminal", "exec", "cmd"]):
                return f'run_terminal_command(cmd="{arg_str}")'
            elif any(k in norm_tool for k in ["sql", "db", "query"]):
                return f'execute_sql(query="{arg_str}")'
            elif any(k in norm_tool for k in ["http", "curl", "fetch", "url", "web"]):
                return f'http_get(url="{arg_str}")'
            elif any(k in norm_tool for k in ["file", "read", "open"]):
                return f'read_file(path="{arg_str}")'
            else:
                return f'{tool_name}({arg_str})'

    def inspect_tool_call(self, tool_name: str, arguments: Any) -> Dict[str, Any]:
        """
        Full 3-Layer evaluation:
        Layer 1: Deterministic SSRF & Cloud Metadata Validator
        Layer 2: AST Normalizer & Recursive Deobfuscation Heuristics
        Layer 3: Qwen2.5-Coder Machine Learning Evaluation
        """
        t_start = time.perf_counter()
        if not isinstance(tool_name, str) or not tool_name.strip():
            return {
                "decision": "BLOCK",
                "verdict": "BLOCKED",
                "risk_score": 100.0,
                "confidence": 1.0,
                "reason": "Invalid or missing tool name",
                "flagged_by": "VALIDATION_ERROR",
                "latency_ms": 0.0,
                "layer3": "skipped",
                "tool_name": str(tool_name)
            }

        norm_tool = tool_name.lower().strip()
        raw_str = str(arguments) if not isinstance(arguments, str) else arguments
        is_net_tool = any(k in norm_tool for k in ["http", "fetch", "url", "curl", "web_search", "browse", "download", "request"])

        # Quick in-memory cache lookup (full-hash, skip network tools to prevent DNS rebinding bypass)
        cache_key = None
        if not is_net_tool:
            cache_key = hashlib.sha256(f"{norm_tool}::{raw_str}".encode("utf-8")).hexdigest()
            with self._cache_lock:
                if cache_key in self._cache:
                    hit = dict(self._cache[cache_key])
                    hit["latency_ms"] = round((time.perf_counter() - t_start) * 1000.0, 2)
                    self._cache.move_to_end(cache_key)
                    return hit

        # ----------------------------------------------------------------------
        # LAYER 1: SSRF & Cloud Metadata Defense (Instant Deterministic Block)
        # ----------------------------------------------------------------------
        # Extract all potential targets from arguments
        candidate_strings = iter_strings(arguments)
        if is_net_tool:
            target_candidates = candidate_strings or [raw_str]
        else:
            # Check if any argument string looks like a URL or Cloud IMDS target
            target_candidates = [s for s in candidate_strings if any(k in s for k in ["://", "169.254.169.254", "100.100.100.200", "metadata", "localhost"])]

        for target in target_candidates:
            is_blocked, ssrf_reason, resolved_ip = SSRFFilter.inspect_target(target)
            if is_blocked:
                latency_ms = round((time.perf_counter() - t_start) * 1000.0, 2)
                return {
                    "decision": "BLOCK",
                    "verdict": "BLOCKED",
                    "risk_score": 100.0,
                    "confidence": 1.0,
                    "reason": ssrf_reason,
                    "flagged_by": "SSRF_FILTER",
                    "resolved_ip": resolved_ip,
                    "latency_ms": latency_ms,
                    "layer3": "skipped",
                    "tool_name": tool_name
                }

        # ----------------------------------------------------------------------
        # LAYER 2: AST & De-Obfuscation Inspection (Deterministic Heuristics)
        # ----------------------------------------------------------------------
        # Inspect raw string representation and all constituent strings
        strings_to_inspect = [raw_str] + [s for s in candidate_strings if s != raw_str]
        for s in strings_to_inspect:
            normalized_text, deterministic_threat = PayloadNormalizer.inspect(s)
            if deterministic_threat:
                latency_ms = round((time.perf_counter() - t_start) * 1000.0, 2)
                return {
                    "decision": "BLOCK",
                    "verdict": "BLOCKED",
                    "risk_score": 99.0,
                    "confidence": 0.99,
                    "reason": deterministic_threat,
                    "flagged_by": "AST_NORMALIZER",
                    "normalized_payload": normalized_text[:512],
                    "latency_ms": latency_ms,
                    "layer3": "skipped",
                    "tool_name": tool_name
                }

        # ----------------------------------------------------------------------
        # LAYER 3: Qwen2.5-Coder Model Evaluation
        # ----------------------------------------------------------------------
        self._lazy_load_model()
        formatted_call = self._format_tool_call_string(tool_name, arguments)
        layer3_status = "fallback"

        if self._model is not None and self._tokenizer is not None:
            try:
                import torch
                inputs = self._tokenizer(
                    formatted_call,
                    return_tensors="pt",
                    truncation=True,
                    max_length=256
                ).to(self.device)

                with torch.inference_mode():
                    logits = self._model(**inputs).logits
                    probs = torch.softmax(logits, dim=-1)[0]
                    label2id = getattr(self._model.config, "label2id", {})
                    mal_idx = label2id.get("MALICIOUS", 1)
                    malicious_prob = probs[mal_idx].item()

                risk_score = round(malicious_prob * 100.0, 2)
                latency_ms = round((time.perf_counter() - t_start) * 1000.0, 2)
                layer3_status = "ok"

                if risk_score >= 70.0:
                    return {
                        "decision": "BLOCK",
                        "verdict": "BLOCKED",
                        "risk_score": risk_score,
                        "confidence": round(malicious_prob, 3),
                        "reason": "Adversarial tool manipulation / injection flagged by Qwen2.5-Coder Guardrail",
                        "flagged_by": "QWEN2.5_CODER_GUARDRAIL",
                        "formatted_call": formatted_call,
                        "latency_ms": latency_ms,
                        "layer3": layer3_status,
                        "tool_name": tool_name
                    }
                else:
                    res = {
                        "decision": "ALLOW",
                        "verdict": "ALLOWED",
                        "risk_score": risk_score,
                        "confidence": round(1.0 - malicious_prob, 3),
                        "reason": "Verified safe tool call",
                        "flagged_by": "CLEAN",
                        "formatted_call": formatted_call,
                        "latency_ms": latency_ms,
                        "layer3": layer3_status,
                        "tool_name": tool_name
                    }
                    if cache_key:
                        with self._cache_lock:
                            if len(self._cache) >= self._cache_max:
                                self._cache.popitem(last=False)
                            self._cache[cache_key] = res
                    return res
            except Exception:
                layer3_status = "error"

        # Clean fallback if no threat detected
        latency_ms = round((time.perf_counter() - t_start) * 1000.0, 2)
        res = {
            "decision": "ALLOW",
            "verdict": "ALLOWED",
            "risk_score": 0.0,
            "confidence": 1.0,
            "reason": "Allowed by deterministic policy (degraded ML fallback)",
            "flagged_by": "CLEAN",
            "formatted_call": formatted_call,
            "latency_ms": latency_ms,
            "layer3": layer3_status,
            "degraded": True,
            "tool_name": tool_name
        }
        if cache_key:
            with self._cache_lock:
                if len(self._cache) >= self._cache_max:
                    self._cache.popitem(last=False)
                self._cache[cache_key] = res
        return res


# Global singleton instance
tool_guardrail = AgenticToolGuardrail()
